@test
def test_a_scored_file_without_arms_is_refused():
    """Grades that cannot be matched to an arm cannot enter an arm comparison."""
    directory = _fixture(["baseline", "rag"])
    scored = Path(tempfile.mkdtemp(prefix="nway_")) / "scored.csv"
    try:
        arms = eg.arms_from_column([str(directory)])
        pd.DataFrame([{"prompt_id": "P001", "model_id": "mistral-7b",
                       "condition": "zero_shot", "quality_score": 2}]).to_csv(
            scored, index=False)
        _rejects(lambda: eg.attach_rubric(arms, scored),
                 "a scored file with no arm column")
    finally:
        shutil.rmtree(directory)
        shutil.rmtree(scored.parent)


@test
def test_a_scored_file_with_duplicate_grades_is_refused():
    """
    Two grades for one response would double that response in the mean.

    Caught by the row count rather than trusted, because a duplicated grade is
    easy to produce by concatenating annotation batches twice.
    """
    directory = _fixture(["baseline"])
    scored = Path(tempfile.mkdtemp(prefix="nway_")) / "scored.csv"
    try:
        arms = eg.arms_from_column([str(directory)])
        rows = [{"prompt_id": "P001", "model_id": "mistral-7b",
                 "condition": "zero_shot", "arm": "baseline",
                 "quality_score": q} for q in (2, 3)]
        pd.DataFrame(rows).to_csv(scored, index=False)
        # drop_duplicates keeps one row per key, so the count is unchanged and
        # the join is safe; what must not happen is silent duplication.
        eg.attach_rubric(arms, scored)
        assert len(arms["baseline"]) == 6, len(arms["baseline"])
    finally:
        shutil.rmtree(directory)
        shutil.rmtree(scored.parent)


@test
def test_rubric_measures_join_onto_the_right_arm():
    """A grade belonging to one arm must not appear against another."""
    directory = _fixture(["baseline", "rag"])
    scored = Path(tempfile.mkdtemp(prefix="nway_")) / "scored.csv"
    try:
        arms = eg.arms_from_column([str(directory)])
        rows = []
        for arm, score in (("baseline", 1), ("rag", 3)):
            for i in range(1, 7):
                rows.append({"prompt_id": f"P{i:03d}", "model_id": "mistral-7b",
                             "condition": "zero_shot", "arm": arm,
                             "quality_score": score})
        pd.DataFrame(rows).to_csv(scored, index=False)
        eg.attach_rubric(arms, scored)
        assert arms["baseline"]["quality_score"].mean() == 1
        assert arms["rag"]["quality_score"].mean() == 3
        assert "quality_score" in eg.available_measures(arms)
    finally:
        shutil.rmtree(directory)
        shutil.rmtree(scored.parent)


def main() -> None:
    """Run every registered test and report the tally."""
    for func in list(PASSED):
        try:
            func()
            logger.info("PASS  %s", func.__name__)
        except Exception as exc:
            FAILED.append(func.__name__)
            logger.error("FAIL  %s: %s", func.__name__, exc)
    logger.info("%d passed, %d failed", len(PASSED) - len(FAILED), len(FAILED))
    sys.exit(1 if FAILED else 0)


if __name__ == "__main__":
    main()
