@test
def test_the_ladder_compares_adjacent_rungs_only():
    """
    Each layer is tested against the one below it, not against the first.

    Comparing everything to baseline would answer "is the whole stack better",
    which is not the claim; the claim is that each added layer earns its place.
    """
    directory = _fixture(["baseline", "rag", "routed"])
    try:
        arms = eg.arms_from_column([str(directory)])
        ladder = eg.compare_ladder(arms, ["baseline", "rag", "routed"],
                                   ["completion_tokens"], by_run=False)
        assert list(ladder["step"]) == ["baseline -> rag", "rag -> routed"], \
            list(ladder["step"])
    finally:
        shutil.rmtree(directory)


@test
def test_the_ladder_order_is_respected():
    """The order given is the order compared, not alphabetical."""
    directory = _fixture(["baseline", "rag", "routed"])
    try:
        arms = eg.arms_from_column([str(directory)])
        ladder = eg.compare_ladder(arms, ["routed", "rag", "baseline"],
                                   ["completion_tokens"], by_run=False)
        assert list(ladder["step"]) == ["routed -> rag", "rag -> baseline"], \
            list(ladder["step"])
    finally:
        shutil.rmtree(directory)


@test
def test_a_measure_missing_from_one_arm_is_excluded_from_all():
    """
    Otherwise an arm would be compared on a measure only it carries.

    That would produce a column with a number for one arm and a blank for the
    rest, which reads as a result rather than as a gap.
    """
    directory = _fixture(["baseline", "rag"])
    try:
        arms = eg.arms_from_column([str(directory)])
        arms["rag"]["bertscore_f1"] = 0.87
        measures = eg.available_measures(arms)
        assert "bertscore_f1" not in measures, measures
        assert "completion_tokens" in measures, measures
    finally:
        shutil.rmtree(directory)


@test
def test_the_summary_is_wide_with_one_row_per_measure():
    """The report's headline table: measures down, arms across."""
    directory = _fixture(["baseline", "rag", "routed"])
    try:
        arms = eg.arms_from_column([str(directory)])
        order = ["baseline", "rag", "routed"]
        summary = eg.summarise_arms(arms, ["completion_tokens", "complete"], order)
        assert list(summary["measure"]) == ["completion_tokens", "complete"]
        for name in order:
            assert name in summary.columns, f"{name} missing from the summary"
        assert int(summary["n_per_arm"].iloc[0]) == 6
    finally:
        shutil.rmtree(directory)


